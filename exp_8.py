# Commented out IPython magic to ensure Python compatibility.

# ============================================================
# EXPERIMENT: STRUCTURED VS UNSTRUCTURED LLM OUTPUT
# ============================================================

# STEP 1: Install Gemini SDK
# %pip install -q -U google-genai

# STEP 2: Import libraries
from getpass import getpass
from google import genai
from google.genai import errors
import time
import re

# STEP 3: Configure Gemini API
API_KEY = getpass("Enter your Gemini API key: ")
client = genai.Client(api_key=API_KEY)

MODEL = "gemini-3.8-flash"
TEMPERATURE = 0.2

# ============================================================
# STEP 4: Define both prompts
# ============================================================

unstructured_prompt = """
Describe Python, Java, and C++ in a short paragraph.
Explain their typing systems, primary use cases, and difficulty
levels for beginners.
"""

structured_prompt = """
Describe Python, Java, and C++ using a Markdown table only.

The table must contain exactly these columns:
Language | Typing (static/dynamic) | Primary Use Case |
Difficulty (Beginner/Intermediate/Advanced)

Include exactly three data rows: Python, Java, and C++.

Use these guidelines:
- Python: dynamically typed.
- Java: statically typed.
- C++: statically typed.
- Assign a reasonable difficulty level for a typical beginner.
- Keep each use case concise.
- Do not output JSON.
- Do not add explanatory text outside the Markdown table.
"""

# ============================================================
# STEP 5: Generate response with retry
# ============================================================

def generate_with_retry(prompt):
    for attempt in range(4):
        try:
            return client.models.generate_content(
                model=MODEL,
                contents=prompt,
                config={"temperature": TEMPERATURE}
            )

        except errors.ServerError:
            if attempt == 3:
                raise

            wait_seconds = 2 ** (attempt + 1)
            print(
                f"Temporary server error. Retrying in "
                f"{wait_seconds} seconds..."
            )
            time.sleep(wait_seconds)

# ============================================================
# STEP 6: Send both prompts to the LLM
# ============================================================

try:
    unstructured_response = generate_with_retry(unstructured_prompt)
    structured_response = generate_with_retry(structured_prompt)

    unstructured_text = unstructured_response.text or ""
    structured_text = structured_response.text or ""

    # ========================================================
    # STEP 7: Print both outputs
    # ========================================================

    print("\n========== UNSTRUCTURED OUTPUT ==========\n")
    print(unstructured_text)

    print("\n========== STRUCTURED OUTPUT (MARKDOWN TABLE) ==========\n")
    print(structured_text)

    # ========================================================
    # STEP 8: Check required table columns and rows
    # ========================================================

    print("\n========== STRUCTURED OUTPUT VALIDATION ==========")

    required_columns = [
        "Language",
        "Typing (static/dynamic)",
        "Primary Use Case",
        "Difficulty (Beginner/Intermediate/Advanced)"
    ]

    required_languages = ["Python", "Java", "C++"]

    # Find Markdown table rows
    table_lines = [
        line.strip()
        for line in structured_text.splitlines()
        if line.strip().startswith("|")
    ]

    # Ignore the Markdown separator row
    data_rows = [
        line for line in table_lines
        if not re.fullmatch(r"\|?[\s|:-]+\|?", line)
    ]

    # Extract cells from the table
    parsed_rows = [
        [cell.strip() for cell in line.strip("|").split("|")]
        for line in data_rows
    ]

    if parsed_rows:
        header = parsed_rows[0]
        print("Table detected: YES")

        for column in required_columns:
            found = any(
                column.lower() == cell.lower()
                for cell in header
            )
            print(
                f"Column '{column}': "
                f"{'PASS' if found else 'FAIL'}"
            )

        actual_languages = [
            row[0].lower()
            for row in parsed_rows[1:]
            if row
        ]

        for language in required_languages:
            found = language.lower() in actual_languages
            print(
                f"Row '{language}': "
                f"{'PASS' if found else 'FAIL'}"
            )

        print(
            "Exactly 3 language rows:",
            "PASS" if len(parsed_rows) - 1 == 3 else "FAIL"
        )

    else:
        print("Table detected: NO")
        print("The response may need manual review.")

    # ========================================================
    # STEP 9: Readability analysis
    # ========================================================

    print("\n========== READABILITY ANALYSIS ==========")

    print("""
1. UNSTRUCTURED OUTPUT:
   - Presents the information in natural paragraph form.
   - Reads like a short explanation.
   - Readers may need to search the paragraph to compare languages.

2. STRUCTURED OUTPUT:
   - Organizes information into clearly labelled columns.
   - Makes typing systems, use cases, and difficulty easier to compare.
   - Is useful for reports, documentation, and quick reference.

3. CONCLUSION:
   Structured output improves comparison and information retrieval.
   Unstructured output is more natural for general explanations.
   Both formats are useful for different purposes.
""")

except errors.ClientError as e:
    print("\nGemini API request failed.")
    print("Check your API key and model availability.")
    print("Details:", e)

except Exception as e:
    print("\nUnexpected error:", e)

